-- Enable vector extension
create extension if not exists vector;

-- Table: Cities
create table public.cities (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  name text not null,
  region text,
  intro_html text,
  latitude numeric,
  longitude numeric,
  is_published boolean default false,
  venue_count int default 0,
  created_at timestamptz default now()
);

-- Table: Venues
create table public.venues (
  id uuid primary key default gen_random_uuid(),
  city_id uuid references public.cities on delete cascade not null,
  slug text not null,
  name text not null,
  google_place_id text unique,
  address text,
  district text,
  latitude numeric,
  longitude numeric,
  phone text,
  website text,
  hours_json jsonb,
  description text,                          -- IA generated + human edited
  description_ai_version text,               -- version of the prompt that generated description
  description_edited_by_human boolean default false,
  highlights text[],                         -- ['Terraza', 'Cervecero', ...]
  serves_eg_bodega boolean default true,
  served_with_bodega_glass boolean,
  served_temperature_ok boolean,
  pour_quality_ai_score numeric,             -- 0-1, from reviews
  pour_quality_ai_notes text,
  cluster_tags text[],                       -- ['clasicos', 'tranquilos'], assigned by AI
  cover_image_url text,
  embedding vector(1024),                    -- Voyage embedding (similarity/duplicate check)
  status text check (status in ('draft','published','archived')) default 'draft',
  published_at timestamptz,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  unique (city_id, slug)
);

-- Table: Venue Suggestions
create table public.venue_suggestions (
  id uuid primary key default gen_random_uuid(),
  city_id uuid references public.cities,
  city_name_freetext text,
  venue_name text not null,
  address text,
  google_place_id text,
  notes text,
  submitter_email text,
  notify_when_published boolean default false,
  ai_quality_score numeric,                  -- 0-1 generated by AI moderator
  ai_classification text,                    -- 'high_quality','duplicate','spam','out_of_scope'
  ai_duplicate_of uuid references public.venues,
  ai_notes text,
  ai_processed_at timestamptz,
  ai_prompt_version text,
  status text check (status in ('pending','approved','rejected','duplicate')) default 'pending',
  reviewed_at timestamptz,
  review_notes text,
  created_at timestamptz default now()
);

-- Row Level Security (RLS)
alter table public.cities enable row level security;
alter table public.venues enable row level security;
alter table public.venue_suggestions enable row level security;

-- Policies for public access (anon/authenticated)
create policy "Allow public select for published cities" on public.cities
  for select to public using (is_published = true);

create policy "Allow public select for published venues" on public.venues
  for select to public using (status = 'published');

-- Policy for anonymous suggestions creation, no select policy is defined to restrict suggestions select only to service_role
create policy "Allow public insert for suggestions" on public.venue_suggestions
  for insert to public with check (true);

-- Trigger function for updated_at in venues
create or replace function public.handle_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger set_updated_at
before update on public.venues
for each row
execute function public.handle_updated_at();

-- Indexes for performance
create index idx_venues_city_status on public.venues (city_id, status);
create index idx_venue_suggestions_status_created on public.venue_suggestions (status, created_at);
